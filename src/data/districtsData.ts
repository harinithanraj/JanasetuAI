// Helper to compute actual live numbers dynamically from recorded citizen requests
export const computeLiveTotals = (
  requests: any[] = [],
  clusters: any[] = [],
  recommendations: any[] = []
) => {
  const uniqueDistricts = new Set(
    requests
      .map((r) => r.location?.district?.trim().toLowerCase())
      .filter(Boolean)
  ).size;

  const activeNeeds = requests.filter((r) => r.status !== 'Resolved').length;
  const estimatedCitizensImpacted = requests.reduce(
    (acc, r) => acc + (Number(r.estimatedPeopleAffected) || 0),
    0
  );

  return {
    totalCitizenRequests: requests.length,
    activeDevelopmentNeeds: activeNeeds,
    highPriorityHotspots: clusters.length,
    districtsAnalysed: uniqueDistricts,
    requestsThisMonth: requests.length,
    aiRecommendations: recommendations.length,
    estimatedCitizensImpacted,
  };
};
